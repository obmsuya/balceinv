import assert from 'node:assert/strict'
import { normalizePhone, detectProvider, formatPhone, describeDuration, formatShillings } from '../app/utils/mobileMoney.ts'

assert.equal(normalizePhone('0712 345 678'), '0712345678')
assert.equal(normalizePhone('+255 712-345-678'), '0712345678')
assert.equal(normalizePhone('255712345678'), '0712345678')
assert.equal(normalizePhone('712345678'), '0712345678')
assert.equal(normalizePhone('0612345678'), '0612345678')
assert.equal(normalizePhone('071234567'), null)
assert.equal(normalizePhone('0512345678'), null)
assert.equal(normalizePhone(''), null)
assert.equal(detectProvider('0754 000 000'), 'Mpesa')
assert.equal(detectProvider('+255 68 000 0000'), 'Airtel')
assert.equal(detectProvider('0715'), 'Tigo')
assert.equal(detectProvider('062'), 'Halopesa')
assert.equal(detectProvider('07'), null)
assert.equal(detectProvider('0799000000'), null)
assert.equal(formatPhone('0712345678'), '0712 345 678')
assert.equal(formatPhone('+255712'), '0712')
assert.equal(describeDuration(30), '1 month')
assert.equal(describeDuration(90), '3 months')
assert.equal(describeDuration(365), '1 year')
assert.equal(describeDuration(14), '14 days')
assert.equal(formatShillings('15000.00'), 'TSh 15,000')
assert.equal(formatShillings('abc'), '')
console.log('mobileMoney checks passed')
